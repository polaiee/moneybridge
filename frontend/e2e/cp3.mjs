import { launch, check, BASE } from './lib.mjs'
const { browser, page, errors } = await launch({ width: 1280, height: 900 })
await page.goto(BASE)
await page.evaluate(() => localStorage.setItem('mb.profile', JSON.stringify({ name: 'Alex Morgan', stage: 'early_career', level: 'beginner', goals: ['investing'], dataSetup: 'demo' })))
await page.goto(BASE + '/twin')
await page.getByText('Illustrative ending value').waitFor()
const main = () => page.locator('main').innerText()
check('starting portfolio is the demo $12,000', (await main()).includes('$12,000'))
// reference case from CLAUDE.md: $10k, $300/mo, 6%, 0.05% fee, 10y => $67,134
await page.fill('#initial', '10000'); await page.fill('#baseMonthly', '300')
await page.locator('input[aria-label="Demo US Equity ETF weight"]').fill('100')
await page.locator('input[aria-label="Demo International ETF weight"]').fill('0')
await page.waitForFunction(() => document.querySelector('main').innerText.includes('$67,134'), null, { timeout: 8000 }).catch(() => {})
let t = await main()
check('reference case ending value $67,134', t.includes('$67,134'))
check('total contributed $46,000', t.includes('$46,000'))
check('modeled growth $21,134', t.includes('$21,134'))
check('allocation total OK message', t.includes('Allocation totals 100%'))
// validation
await page.locator('#w1').fill('30')
check('invalid allocation shows error', await page.getByText('Allocation must total 100% (currently 130%)').isVisible())
check('Run Simulation disabled when invalid', await page.getByRole('button', { name: 'Run Simulation' }).isDisabled())
await page.getByRole('button', { name: /Set last fund/ }).click()
check('"set remaining" fixes total', (await main()).includes('Allocation totals 100%'))
await page.fill('#years', '0'); check('years validation', await page.getByText('Duration must be between 1 and 50').isVisible())
await page.fill('#years', '20'); await page.waitForTimeout(900)
check('years 20 recomputes (chart end label & text)', (await main()).includes('over 20 years'))
// change allocation and ensure the numbers move vs API truth
await page.fill('#years', '10'); await page.fill('#monthly', '500'); await page.waitForTimeout(1200)
const truth = await (await fetch('http://127.0.0.1:8000/api/simulate', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ scenario: { initial_investment: 10000, monthly_contribution: 500, years: 10, gross_return_pct: 6, holdings: [{ name: 'a', weight_pct: 100, expense_ratio_pct: 0.05 }, { name: 'b', weight_pct: 0, expense_ratio_pct: 0.2 }] } }) })).json()
const fmt = (n) => '$' + Math.round(n).toLocaleString('en-US')
check('UI matches backend for $500/mo', (await main()).includes(fmt(truth.hypothetical.ending_value)), fmt(truth.hypothetical.ending_value))
check('risk scenarios shown', (await main()).includes('Downside') && (await main()).includes('Upside'))
check('disclaimers visible', (await main()).includes('not forecasts') && (await main()).includes('Capital can be lost'))
check('Explain button present', await page.getByRole('button', { name: 'Explain This Scenario' }).first().isVisible())
await page.getByRole('radio', { name: /Fund A/ }).click(); check('quiz gives feedback', await page.getByText('Correct.').isVisible())
await page.fill('#initial', '12000'); await page.fill('#monthly', '300'); await page.waitForTimeout(900)
await page.screenshot({ path: process.env.SHOT, fullPage: true })
check('no console errors', errors.length === 0, errors.join(' | '))
await browser.close()
