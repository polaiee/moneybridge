import { launch, check, BASE } from './lib.mjs'
const { browser, page, errors } = await launch()
await page.goto(BASE)
await page.evaluate(() => localStorage.setItem('mb.profile', JSON.stringify({ name: 'Alex Morgan', stage: 'early_career', level: 'beginner', goals: ['emergency_savings', 'investing'], dataSetup: 'demo' })))
await page.goto(BASE + '/dashboard')
await page.getByRole('heading', { name: /Your financial overview/ }).waitFor()
const api = await (await fetch('http://127.0.0.1:8000/api/dashboard')).json()
const text = await page.locator('main').innerText()
for (const [k, v] of [['net worth', api.net_worth], ['assets', api.total_assets], ['liabilities', api.total_liabilities], ['surplus', api.cash_flow.monthly_surplus]])
  check(`${k} on page matches API`, text.includes('$' + v.toLocaleString('en-US')), '$' + v)
check('net worth = 22,000', api.net_worth === 22000 && text.includes('$22,000'))
check('4 accounts listed', (await page.locator('[data-account]').count()) === 4)
check('demo labels shown', (await page.getByText('Demo data', { exact: true }).count()) >= 6)
check('roadmap has goal links', await page.getByRole('link', { name: /Browse savings/ }).isVisible() && await page.getByRole('link', { name: /Open Financial Twin/ }).first().isVisible())
await page.getByRole('link', { name: /Explore in Financial Twin/ }).click(); await page.waitForURL('**/twin'); check('CTA goes to twin', true)
check('no console errors', errors.length === 0, errors.join(' | '))
await page.goto(BASE + '/dashboard'); await page.getByRole('heading', { name: /Your financial overview/ }).waitFor(); await page.waitForTimeout(600)
await page.screenshot({ path: process.env.SHOT, fullPage: true })
await browser.close()
