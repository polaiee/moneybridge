import { launch, check, BASE } from './lib.mjs'
const { browser, page, errors } = await launch()
await page.goto(BASE)
await page.evaluate(() => { localStorage.clear(); localStorage.setItem('mb.profile', JSON.stringify({ name: 'Alex Morgan', stage: 'early_career', level: 'beginner', goals: ['investing'], dataSetup: 'demo' })); localStorage.setItem('mb.memory', 'true'); localStorage.setItem('mb.shareProfile', 'true') })
await page.goto(BASE + '/twin'); await page.getByText('Illustrative ending value').waitFor()
const ending = (await page.locator('main').innerText()).match(/Illustrative ending value\s+(\$[\d,]+)/i)[1]
let chatBody = null
const dollars = (t) => [...t.matchAll(/\$\s?([\d,]+(?:\.\d+)?)/g)].map((m) => Number(m[1].replace(/,/g, '')))
page.on('request', (r) => { if (r.url().endsWith('/api/chat') && r.method() === 'POST') chatBody = JSON.parse(r.postData()) })
await page.getByRole('region', { name: 'Summary' }).getByRole('button', { name: 'Explain This Scenario' }).click()
await page.getByRole('dialog').waitFor()
check('AI panel opens in-page (stays on /twin)', page.url().endsWith('/twin'))
await page.getByTestId('ai-reply').waitFor({ timeout: 90000 })
const panel = await page.getByRole('dialog').innerText()
const exact = chatBody.scenario_results.results.hypothetical.ending_value.toLocaleString('en-US', { minimumFractionDigits: 2 })
console.log('backend ending value sent to Backboard:', exact)
check('request sent scenario_results from the backend (live Backboard)', !!chatBody?.scenario_results?.results?.hypothetical)
const endVal = chatBody.scenario_results.results.hypothetical.ending_value, rep = await page.getByTestId('ai-reply').innerText()
check('AI PANEL reply quotes the exact backend ending value ($' + endVal + '), compared numerically', dollars(rep).includes(endVal), 'dollar amounts in reply: ' + [...new Set(dollars(rep))].join(', '))
check('AI panel reply also quotes the backend cost of fees and downside/upside values', [chatBody.scenario_results.results.fee_impact.cost_of_fees, chatBody.scenario_results.results.risk_scenarios.downside.ending_value, chatBody.scenario_results.results.risk_scenarios.upside.ending_value].every((n) => dollars(rep).includes(n)))
check('AI panel labels the context used', panel.includes('Financial Twin results'))
console.log('---AI PANEL REPLY (first 700 chars)---\n' + (await page.getByTestId('ai-reply').innerText()).slice(0, 700))
await page.getByRole('button', { name: 'Continue in AI Companion' }).click(); await page.waitForURL('**/companion')
await page.getByText('Used:').first().waitFor({ timeout: 20000 })
const reply = null
const txt = await page.locator('main').innerText()
check('Companion continues the same conversation (panel Q&A present)', txt.includes('Explain this Financial Twin scenario') && dollars(txt).includes(endVal))
check('assistant replied (non-empty)', txt.length > 400)
check('reply labeled with Financial Twin context', txt.includes('Financial Twin results'))
check('Companion thread shows the app-calculated ending value $' + endVal, dollars(txt).includes(endVal))
const th = await page.evaluate(() => localStorage.getItem('mb.thread')); check('thread id persisted', !!th && th !== 'null')
// follow-up on same thread
await page.getByLabel('Message', { exact: true }).fill('In one sentence, what was my fee about?'); await page.getByRole('button', { name: 'Send' }).click()
await page.getByText('Thinking…').waitFor().catch(() => {}); await page.getByText('Thinking…').waitFor({ state: 'detached', timeout: 90000 })
check('follow-up answered', (await page.locator('main').innerText()).split('Educational explanation').length >= 3)
// reload persistence
await page.reload(); await page.getByText('Used:').first().waitFor()
check('chat history survives reload', (await page.locator('main').innerText()).includes('Explain this Financial Twin scenario'))
const mem = await fetch('http://127.0.0.1:8000/api/memory'); check('/api/memory responds', mem.ok, String(mem.status))
let before = 0
for (let i = 0; i < 8 && before === 0; i++) { await page.getByRole('button', { name: 'Refresh' }).click(); await page.waitForTimeout(3000); before = await page.getByRole('button', { name: 'Delete memory' }).count() }
check('memory panel lists retained memories', before > 0, String(before))
await page.getByRole('button', { name: 'Delete memory' }).first().click(); await page.waitForTimeout(1500)
check('deleting a memory removes it', (await page.getByRole('button', { name: 'Delete memory' }).count()) === before - 1)
await page.screenshot({ path: process.env.SHOT, fullPage: true })
console.log('---REPLY---\n' + txt.slice(txt.indexOf('Explain this'), txt.indexOf('Explain this') + 1500))
check('no console errors', errors.length === 0, errors.join(' | '))
await browser.close()
