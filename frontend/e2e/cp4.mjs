import { launch, check, BASE } from './lib.mjs'
const { browser, page, errors } = await launch()
await page.goto(BASE)
await page.evaluate(() => { localStorage.clear(); localStorage.setItem('mb.profile', JSON.stringify({ name: 'Alex Morgan', stage: 'early_career', level: 'beginner', goals: ['investing'], dataSetup: 'demo' })); localStorage.setItem('mb.memory', 'true'); localStorage.setItem('mb.shareProfile', 'true') })
await page.goto(BASE + '/twin'); await page.getByText('Illustrative ending value').waitFor()
const ending = (await page.locator('main').innerText()).match(/Illustrative ending value\s+(\$[\d,]+)/)[1]
await page.getByRole('button', { name: 'Explain This Scenario' }).click()
await page.waitForURL('**/companion')
const reply = page.locator('div.bg-canvas').last()
await page.getByText('Used:').waitFor({ timeout: 90000 })
const txt = await page.locator('main').innerText()
check('assistant replied (non-empty)', txt.length > 400)
check('reply labeled with Financial Twin context', txt.includes('Financial Twin results'))
check('reply mentions the app-calculated ending value ' + ending, txt.includes('70,466.50'))
const th = await page.evaluate(() => localStorage.getItem('mb.thread')); check('thread id persisted', !!th && th !== 'null')
// follow-up on same thread
await page.getByLabel('Message').fill('In one sentence, what was my fee about?'); await page.getByRole('button', { name: 'Send' }).click()
await page.getByText('Thinking…').waitFor().catch(() => {}); await page.getByText('Thinking…').waitFor({ state: 'detached', timeout: 90000 })
check('follow-up answered', (await page.locator('main').innerText()).split('Educational explanation').length >= 3)
// reload persistence
await page.reload(); await page.getByText('Used:').first().waitFor()
check('chat history survives reload', (await page.locator('main').innerText()).includes('Explain this Financial Twin scenario'))
const mem = await fetch('http://127.0.0.1:8000/api/memory'); check('/api/memory responds', mem.ok, String(mem.status))
const before = await page.getByRole('button', { name: 'Delete memory' }).count()
check('memory panel lists retained memories', before > 0, String(before))
await page.getByRole('button', { name: 'Delete memory' }).first().click(); await page.waitForTimeout(1500)
check('deleting a memory removes it', (await page.getByRole('button', { name: 'Delete memory' }).count()) === before - 1)
await page.screenshot({ path: process.env.SHOT, fullPage: true })
console.log('---REPLY---\n' + txt.slice(txt.indexOf('Explain this'), txt.indexOf('Explain this') + 1500))
check('no console errors', errors.length === 0, errors.join(' | '))
await browser.close()
