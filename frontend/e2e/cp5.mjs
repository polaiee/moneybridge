import { launch, check, BASE } from './lib.mjs'
const { browser, page, errors } = await launch()
await page.goto(BASE)
await page.evaluate(() => { localStorage.clear(); localStorage.setItem('mb.profile', JSON.stringify({ name: 'Alex Morgan', stage: 'early_career', level: 'beginner', goals: ['emergency_savings', 'investing', 'credit_building'], dataSetup: 'demo' })); localStorage.setItem('mb.memory', 'false') })
await page.goto(BASE + '/marketplace')
await page.getByRole('heading', { name: 'Financial Marketplace' }).waitFor()
await page.getByRole('article').first().waitFor()
check('10 demo products', (await page.getByRole('article').count()) === 10)
check('every card labelled Demo Product', (await page.getByText('Demo Product').count()) === 10)
check('"Relevant to Your Goals" shows max 2 cards', (await page.locator('section[aria-label="Relevant to Your Goals"] button').count()) === 2)
await page.getByPlaceholder('Search products or providers…').fill('harbor'); await page.waitForTimeout(700)
check('search by provider', (await page.getByRole('article').count()) === 2)
await page.getByPlaceholder('Search products or providers…').fill('')
await page.locator('section[aria-label="Relevant to Your Goals"] button').first().click(); await page.waitForTimeout(600)
check('goal card applies category filter', page.url().includes('category=savings') && (await page.getByRole('article').count()) === 3)
await page.getByRole('group', { name: 'Categories' }).getByRole('button', { name: /Credit/ }).click(); await page.waitForTimeout(500)
check('category card filters', (await page.getByRole('article').count()) === 2)
await page.getByRole('group', { name: 'Categories' }).getByRole('button', { name: /Savings/ }).click(); await page.waitForTimeout(500)
await page.getByRole('article', { name: 'Rainy Day Savings' }).getByRole('button', { name: 'View Details' }).click()
check('drawer opens', await page.getByRole('dialog').isVisible() && await page.getByText('Risks and limitations').isVisible())
await page.getByRole('button', { name: 'Add to Compare' }).click(); await page.keyboard.press('Escape')
check('sticky bar appears', await page.getByRole('region', { name: 'Comparison bar' }).isVisible())
check('Compare disabled with 1', await page.getByRole('region', { name: 'Comparison bar' }).getByRole('button', { name: 'Compare' }).isDisabled())
await page.getByRole('article', { name: 'Flexible Savings' }).getByRole('button', { name: 'Compare' }).click()
check('Compare enabled with 2', await page.getByRole('region', { name: 'Comparison bar' }).getByRole('button', { name: 'Compare' }).isEnabled())
await page.getByRole('region', { name: 'Comparison bar' }).getByRole('button', { name: 'Compare' }).click()
await page.getByText('A clearer view, side by side.').waitFor()
const t = await page.locator('table').innerText()
check('table shows both APYs', t.includes('4.00%') && t.includes('3.80%'))
// cross-category rule
await page.getByRole('group', { name: 'Categories' }).getByRole('button', { name: /Credit/ }).click(); await page.waitForTimeout(500)
await page.getByRole('article', { name: 'Starter Secured Card' }).getByRole('button', { name: 'Compare' }).click()
check('cross-category replaces + notice', await page.getByText(/same category/).isVisible() && (await page.getByRole('region', { name: 'Comparison bar' }).innerText()).includes('1 of 2'))
// back to savings and explain
await page.getByRole('group', { name: 'Categories' }).getByRole('button', { name: /Savings/ }).click(); await page.waitForTimeout(500)
await page.getByRole('article', { name: 'Rainy Day Savings' }).getByRole('button', { name: 'Compare' }).click().catch(() => {})
await page.getByRole('region', { name: 'Comparison bar' }).waitFor()
await page.getByRole('region', { name: 'Comparison bar' }).getByRole('button', { name: /Remove Starter/ }).click()
await page.getByRole('article', { name: 'Rainy Day Savings' }).getByRole('button', { name: /Compare/ }).click()
await page.getByRole('article', { name: 'Flexible Savings' }).getByRole('button', { name: /Compare/ }).click()
await page.getByRole('region', { name: 'Comparison bar' }).getByRole('button', { name: 'Compare' }).click()
await page.getByRole('button', { name: 'Explain with MoneyBridge AI' }).click()
await page.waitForURL('**/companion'); await page.getByText('Used:').first().waitFor({ timeout: 90000 })
const c = await page.locator('main').innerText()
check('Companion opened with marketplace context', c.includes('Marketplace comparison'))
check('reply cites compared product data', c.includes('4.00') && c.includes('3.8'))
await page.screenshot({ path: process.env.SHOT })
check('no console errors', errors.length === 0, errors.join(' | '))
await browser.close()
